#!/usr/bin/env python3
"""Generate the crew's roles and schedules from crew.json, so setup (and later changes) never hand-edit cron lines.

  schedules.py init-pack --project P --owner O --plan ORG/PLAN --code ORG/CODE [--code ...] --harness ORG/HARNESS
                         [--workers N] --base examples/domain-pack/crew.json --out crew.json
  schedules.py render    --crew crew.json --out DIR --harness-repo ORG/HARNESS --harness-ref REF
  schedules.py table     --crew crew.json
  schedules.py roles     --crew crew.json            # roles that get a schedule caller, one per line

Cadence rules (override per role under crew.json `schedules.roles.<role>`: `cron` list, `enabled` false):
  worker-*   about every 90 minutes, staggered per worker, none on weekdays in `schedules.avoid_hours_utc`
  lead       four runs a day; pm once a day; health once a day; optimizer weekly
  research, review*: no schedule (they run on demand or on events)
Minutes avoid :00 and :30, where GitHub delays and drops runs most (vendor-doc, observed).
"""
import argparse, json, os, re, sys

DEFAULT_AVOID = list(range(15, 21))  # weekday peak hours of a shared plan, UTC (a conservative default)
LETTERS = "abcdefghij"

def kind_of(role):
    for k in ("worker", "lead", "pm", "research", "health", "optimizer", "review"):
        if role == k or role.startswith(k + "-"): return k
    return "other"

def hours_expr(hours):
    hours = sorted(set(hours))
    if not hours: return None
    parts, start, prev = [], hours[0], hours[0]
    for h in hours[1:]:
        if h == prev + 1: prev = h; continue
        parts.append(f"{start}-{prev}" if prev > start else str(start)); start = prev = h
    parts.append(f"{start}-{prev}" if prev > start else str(start))
    return ",".join(parts)

def off_edge(m):  # never :00 or :30
    return m + 1 if m in (0, 30) else m

def default_cron(role, index, avoid):
    k = kind_of(role)
    if k == "worker":
        m1 = off_edge((7 + 11 * index) % 60); m2 = off_edge((m1 + 30) % 60)
        a = [h for h in range(24) if h % 3 == 0]; b = [h for h in range(24) if h % 3 == 1]
        out = []
        for m, hrs in ((m1, a), (m2, b)):
            wk = hours_expr([h for h in hrs if h not in avoid]); we = hours_expr(hrs)
            if wk: out.append(f"{m} {wk} * * 1-5")
            out.append(f"{m} {we} * * 0,6")
        return out
    if k == "lead": return ["23 6,10,13,22 * * *"]
    if k == "pm": return ["41 8 * * *"]
    if k == "health": return ["17 6 * * *"]
    if k == "optimizer": return ["53 5 * * 6"]
    return []

def plan_for(cfg):
    sch = cfg.get("schedules", {}) or {}
    avoid = sch.get("avoid_hours_utc", DEFAULT_AVOID)
    over = sch.get("roles", {}) or {}
    roles = list(cfg.get("roles", {}).keys())
    seen = {}; result = {}
    for role in roles:
        k = kind_of(role); idx = seen.get(k, 0); seen[k] = idx + 1
        o = over.get(role, {})
        cron = [] if o.get("enabled") is False else (o.get("cron") if "cron" in o else default_cron(role, idx, avoid))
        result[role] = cron
    return result

TEMPLATE = '''# Generated by `crew schedules` (and `crew init`). Do not edit by hand: change `schedules` in crew.json and run
# `crew schedules --apply`. Role: {role}. Cron is UTC; GitHub may delay or drop scheduled runs under load (vendor-doc).
name: crew-schedule-{role}

on:
{schedule}  workflow_dispatch:
    inputs:
      prompt_extra:
        description: Extra instruction for this run
        default: ""

permissions:   # a reusable workflow can only use what its caller grants: role-run.yml needs all of these
  contents: write
  pull-requests: write
  issues: write
  id-token: write
  actions: read

jobs:
  run:
    uses: {harness}/.github/workflows/role-run.yml@{ref}
    with:
      role: {role}
      kind: ${{{{ github.event_name == 'schedule' && 'scheduled' || 'manual' }}}}
      prompt_extra: ${{{{ inputs.prompt_extra }}}}
      plan_repo: {plan}
      harness_repo: {harness}
      harness_ref: {ref}
    secrets: inherit
'''

def render(cfg, out, harness, ref):
    os.makedirs(out, exist_ok=True)
    plan = cfg["repos"]["plan"]; written = []
    for role, cron in plan_for(cfg).items():
        sched = "  schedule:\n" + "".join(f'    - cron: "{c}"\n' for c in cron) if cron else ""
        path = os.path.join(out, f"crew-schedule-{role}.yml")
        open(path, "w").write(TEMPLATE.format(role=role, schedule=sched, harness=harness, ref=ref, plan=plan))
        written.append(path)
    return written

def init_pack(a):
    base = json.load(open(a.base))
    n = max(1, int(a.workers)); workers = [f"worker-{LETTERS[i]}" for i in range(n)]
    roles = ["lead", "pm", "research"] + workers
    base["project"] = a.project; base["owner"] = {"login": a.owner}
    base["repos"] = {"harness": a.harness, "plan": a.plan, "code": a.code}
    base["roles"] = {r: {"app": f"{a.project}-{r}", "trigger": "trig_REPLACE_ME", "secret": re.sub(r"[^A-Z0-9]", "_", r.upper()) + "_FIRE_TOKEN"} for r in roles}
    base["channels"] = {
        "needs-rescue": {"from": workers, "to": "lead", "on_close": "raiser"},
        "needs-owner": {"from": ["lead"], "to": "owner", "on_reply": "raiser", "on_close": workers[0]},
        "debate": {"between": ["pm", "lead"], "turns": 3, "escalate_to": "lead"},
        "needs-research": {"from": ["lead", "pm"] + workers, "to": "research", "on_close": "raiser"},
        "needs-work": {"from": workers, "to": "pm", "on_close": "raiser"},
    }
    base["default_worker"] = workers[0]
    base["schedules"] = {"avoid_hours_utc": DEFAULT_AVOID, "roles": {}}
    json.dump(base, open(a.out, "w"), indent=2); open(a.out, "a").write("\n")

def main():
    ap = argparse.ArgumentParser(); sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init-pack")
    for f in ("project", "owner", "plan", "harness", "base", "out"): p.add_argument("--" + f, required=True)
    p.add_argument("--code", action="append", required=True); p.add_argument("--workers", default=2)
    p = sub.add_parser("render"); p.add_argument("--crew", required=True); p.add_argument("--out", required=True)
    p.add_argument("--harness-repo", required=True); p.add_argument("--harness-ref", default="main")
    for name in ("table", "roles"): sub.add_parser(name).add_argument("--crew", required=True)
    a = ap.parse_args()
    if a.cmd == "init-pack": return init_pack(a)
    cfg = json.load(open(a.crew))
    if a.cmd == "render":
        for f in render(cfg, a.out, a.harness_repo, a.harness_ref): print(os.path.basename(f))
    elif a.cmd == "roles":
        for r in plan_for(cfg): print(r)
    else:
        for r, cron in plan_for(cfg).items(): print(f"{r:14} " + ("  |  ".join(cron) if cron else "(on demand / on events only)"))

if __name__ == "__main__":
    main()
