#!/usr/bin/env bash
# Keeps agent guidance small. Long instructions cost tokens on every run and get followed less;
# guidance belongs in skills (loaded on demand) and scripts (enforced). Fails CI when a limit is exceeded.
# Checks, in the harness checkout: role prompts in prompts/*.md, skills in .claude/skills/*/SKILL.md.
# Checks, in the plan repo: at most 5 active lessons ($PATH_LESSONS, entries are "## L<n> ...").
# Limits are in words. Defaults below; the owner may raise one in crew.json: .limits.words["<file>"] (e.g. "prompts/lead.md").
set -uo pipefail
here=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=lib/crew-env.sh
. "$here/lib/crew-env.sh"
fail=0
check() { # <file> <default-max-words>
  [ -f "$CREW_HARNESS_DIR/$1" ] || return 0
  local w max; w=$(wc -w <"$CREW_HARNESS_DIR/$1" | tr -d ' ')
  max=$(crew_get ".limits.words[\"$1\"]" "$2")
  if [ "$w" -gt "$max" ]; then echo "agent-docs: $1 has $w words (max $max)"; fail=1; fi
}
check prompts/common.md 720
check prompts/lead.md 620
check prompts/worker.md 450
check prompts/optimizer.md 980
check prompts/research.md 420
for f in reviewer health merge-policy; do check "prompts/$f.md" 400; done
check prompts/pm.md 300
# Any other prompt the owner adds gets the default cap.
for f in "$CREW_HARNESS_DIR"/prompts/*.md; do
  b=prompts/$(basename "$f")
  case "$b" in prompts/common.md|prompts/lead.md|prompts/worker.md|prompts/optimizer.md|prompts/research.md|prompts/reviewer.md|prompts/health.md|prompts/merge-policy.md|prompts/pm.md) ;; *) check "$b" 400 ;; esac
done
for f in "$CREW_HARNESS_DIR"/.claude/skills/*/SKILL.md; do
  [ -f "$f" ] || continue
  case "$f" in */skills/openspec-*) continue ;; esac  # generated by the openspec CLI (reference plan format)
  check "${f#"$CREW_HARNESS_DIR"/}" 500
done
# Active lessons: at most 5 entries.
n=$(grep -c '^## L[0-9]' "$CREW_PLAN_DIR/$PATH_LESSONS" 2>/dev/null); n=${n:-0}
[ "$n" -le 5 ] || { echo "agent-docs: $PATH_LESSONS has $n active lessons (max 5); retire into a skill or script"; fail=1; }
[ "$fail" -eq 0 ] && echo "agent-docs: OK"
exit "$fail"
