  ev 'lead\towner tagged you on #8: u\nworker-b\towner tagged you on #8: u' issue_comment '{"issue":{"number":8,"labels":[],"pull_request":{}},"comment":{"html_url":"u","user":{"login":"boss"},"body":"@acme-org/lead and @acme-org/worker-b: look"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"boss"},"body":"<!-- agent -->\n@acme-lead"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"stranger"},"body":"@acme-lead"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"boss"},"body":"@acme-nobody"}}'
  # research informs: her comment's tags wake those roles, never herself; other bots cannot tag
  ev 'pm\tresearch tagged you on #6: u\nworker-b\tresearch tagged you on #6: u' issue_comment '{"issue":{"number":6,"labels":[{"name":"needs-research"}]},"comment":{"html_url":"u","user":{"login":"acme-research[bot]"},"body":"Answer: yes.\n@acme-pm @acme-worker-b @acme-research"}}'
  ev '' issue_comment '{"issue":{"number":6,"labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"acme-research[bot]"},"body":"no tags"}}'
  ev '' issue_comment '{"issue":{"number":8,"labels":[]},"comment":{"user":{"login":"acme-worker-a[bot]"},"body":"@acme-lead"}}'
  ev 'research\towner tagged you on #9: u' issue_comment '{"issue":{"number":9,"labels":[]},"comment":{"html_url":"u","user":{"login":"boss"},"body":"@acme-research what does X cost?"}}'
  # no tag: the role that raised the issue gets the reply, else the lead
  ev 'pm\towner replied on needs-owner #7' issue_comment '{"issue":{"number":7,"body":"x\n<!-- raised-by: pm -->","labels":[{"name":"needs-owner"}]},"comment":{"user":{"login":"boss"},"body":"yes"}}'
  ev 'research\tneeds-research #6 opened' issues '{"action":"labeled","label":{"name":"needs-research"},"issue":{"number":6,"labels":[{"name":"needs-research"}]}}'
  ev 'pm\tneeds-work #16 opened\nlead\tneeds-work #16 opened' issues '{"action":"labeled","label":{"name":"needs-work"},"issue":{"number":16,"labels":[{"name":"needs-work"}]}}'
